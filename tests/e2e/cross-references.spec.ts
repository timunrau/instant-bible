import { test, expect } from '@playwright/test'
import { jump, settled, verseTop } from './helpers'

test.beforeEach(async ({ page }) => {
	await page.goto('/')
	await settled(page)
})

test('BSB footnote citations jump to their passages and Back restores the prior position', async ({ page, isMobile }) => {
	await jump(page, '2 Peter 1:17')
	const verse = page.locator('[data-verse="2pe.1.17"]')
	await verse.click()
	const top = await verseTop(page, '2pe.1.17')
	await verse.locator('.note-marker').click()
	const note = page.getByRole('dialog', { name: 'Scripture footnote' })
	await expect(note).toContainText('1:17 Matthew 17:5; see also Mark 9:7 and Luke 9:35.')
	await expect(note.getByRole('link')).toHaveCount(3)
	await expect(note.getByRole('link', { name: 'Mark 9:7', exact: true })).toHaveAttribute('href', '/Mark/9/7')
	await expect(note.getByRole('link', { name: 'Luke 9:35', exact: true })).toHaveAttribute('href', '/Luke/9/35')
	const entries = await page.evaluate(() => history.length)
	// The dialog starts focused on Close; the citations remain accessible by keyboard.
	await page.keyboard.press('Tab')
	await expect(note.getByRole('link', { name: 'Matthew 17:5', exact: true })).toBeFocused()
	await page.keyboard.press('Enter')
	await expect(note).toHaveCount(0)
	await expect(page).toHaveURL(/\/Matthew\/17\/5$/)
	await expect.poll(() => page.evaluate(() => history.length)).toBe(entries + 1)
	await expect.poll(async () => Math.round(await verseTop(page, 'mat.17.5'))).toBe(isMobile ? 24 : 48)
	await expect(page.locator('.selection-tray')).toHaveCount(0)
	await expect(page.getByRole('button', { name: 'Open reference picker' })).toBeFocused()
	await expect(page.getByRole('button', { name: 'Open reference picker' })).toHaveCSS('outline-style', 'none')
	await page.goBack()
	await expect(page.getByRole('button', { name: 'Open reference picker' })).toHaveText('2 Peter 1')
	await expect.poll(async () => Math.abs(await verseTop(page, '2pe.1.17') - top)).toBeLessThan(3)
})

test('footnote range links work offline without highlighting or selection', async ({ page, context, isMobile }) => {
	await page.evaluate(async () => { await navigator.serviceWorker.ready })
	await page.reload()
	await settled(page)
	await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
	await context.setOffline(true)
	await jump(page, 'Genesis 2:24')
	await page.locator('[data-verse="gen.2.24"] .note-marker').click()
	const note = page.getByRole('dialog', { name: 'Scripture footnote' })
	await note.getByRole('link', { name: 'Mark 10:7–8', exact: true }).click()
	await expect(page).toHaveURL(/\/Mark\/10\/7-8$/)
	await expect.poll(async () => Math.round(await verseTop(page, 'mrk.10.7'))).toBe(isMobile ? 24 : 48)
	await expect(page.locator('[data-verse="mrk.10.7"]')).not.toHaveClass(/indicated/)
	await expect(page.locator('[data-verse="mrk.10.8"]')).not.toHaveClass(/indicated/)
	await expect(page.locator('.selection-tray')).toHaveCount(0)
})

test('unsupported source references stay readable without invented links', async ({ page }) => {
	await jump(page, '2 Peter 2:4')
	await page.locator('[data-verse="2pe.2.4"] .note-marker').click()
	const note = page.getByRole('dialog', { name: 'Scripture footnote' })
	await expect(note).toContainText('1 Enoch 13:1–11 and 1 Enoch 20:1–4')
	await expect(note.getByRole('link')).toHaveCount(0)
})

test('heading references preserve history, selection and native keyboard links', async ({ page, isMobile }) => {
	await jump(page, 'Matthew 1')
	const heading = page.locator('#chapter-mat-1 .reference').first()
	await expect(heading).toHaveText('(Ruth 4:18–22; Luke 3:23–38)')
	await expect(heading.getByRole('link')).toHaveCount(2)
	await expect(heading.getByRole('link').first()).toHaveCSS('text-decoration-line', 'none')
	await expect(heading.getByRole('link', { name: 'Ruth 4:18–22' })).toHaveAttribute('href', '/Ruth/4/18-22')
	await page.locator('[data-verse="mat.1.1"]').first().click()
	const top = await verseTop(page, 'mat.1.1')
	const entries = await page.evaluate(() => history.length)
	const link = heading.getByRole('link', { name: 'Luke 3:23–38' })
	await link.focus()
	await page.keyboard.press('Enter')
	await expect(page).toHaveURL(/\/Luke\/3\/23-38$/)
	await expect.poll(() => page.evaluate(() => history.length)).toBe(entries + 1)
	await expect.poll(async () => Math.round(await verseTop(page, 'luk.3.23'))).toBe(isMobile ? 24 : 48)
	await expect(page.locator('.selection-tray')).toHaveCount(0)
	await expect(page.locator('.indicated')).toHaveCount(0)
	await expect(page.getByRole('button', { name: 'Open reference picker' })).toBeFocused()
	await page.goBack()
	await expect.poll(async () => Math.abs(await verseTop(page, 'mat.1.1') - top)).toBeLessThan(3)
})

test('heading references navigate offline', async ({ page, context }) => {
	await page.evaluate(() => navigator.serviceWorker.ready.then(() => {}))
	await page.reload()
	await settled(page)
	await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true)
	await context.setOffline(true)
	await jump(page, 'Genesis 1')
	await page.locator('#chapter-gen-1 .reference').getByRole('link', { name: 'John 1:1–5' }).click()
	await expect(page).toHaveURL(/\/John\/1\/1-5$/)
	await expect(page.locator('[data-verse="jhn.1.1"]').first()).toContainText('In the beginning was the Word')
})

test('modified heading clicks retain native new-tab behavior', async ({ page, isMobile }) => {
	test.skip(isMobile, 'Desktop modifier interaction')
	const popup = page.context().waitForEvent('page')
	await page.locator('#chapter-gen-1 .reference').getByRole('link', { name: 'John 1:1–5' }).click({ modifiers: ['ControlOrMeta'] })
	const target = await popup
	await expect(target).toHaveURL(/\/John\/1\/1-5$/)
	await expect(page).toHaveURL(/\/Genesis\/1$/)
	await target.close()
})
